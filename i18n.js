  const DEFAULT_LANG = 'zh-Hant';
  let current = DEFAULT_LANG;

  // 正規化語言碼：把 en-US → en、zh-TW → zh-Hant 等對應到支援清單
  function normalize(code) {
    if (!code) return null;
    if (MESSAGES[code]) return code;
    const lower = code.toLowerCase();
    if (lower.startsWith('zh')) {
      if (lower.includes('hans') || lower.includes('cn') || lower.includes('sg')) return 'zh-Hans';
      return 'zh-Hant';
    }
    const base = lower.split('-')[0];
    const hit = LANGS.find((l) => l.code.toLowerCase() === base || l.code.toLowerCase().split('-')[0] === base);
    return hit ? hit.code : null;
  }

  function setLang(code) {
    const n = normalize(code) || DEFAULT_LANG;
    current = n;
    return current;
  }

  function getLang() {
    return current;
  }

  // 取得翻譯字串，支援 {name} 佔位符替換
  function t(key, params) {
    const table = MESSAGES[current] || MESSAGES[DEFAULT_LANG];
    let str = table[key];
    if (str === undefined) str = (MESSAGES[DEFAULT_LANG][key] !== undefined ? MESSAGES[DEFAULT_LANG][key] : key);
    if (params) {
      str = str.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? params[k] : m));
    }
    return str;
  }

  // 依 DOM 上的 data-i18n 屬性套用翻譯
  //   data-i18n            → textContent
  //   data-i18n-placeholder→ placeholder 屬性
  //   data-i18n-title      → title 屬性 / 文件標題
  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach((elm) => {
      elm.textContent = t(elm.getAttribute('data-i18n'));
    });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach((elm) => {
      elm.setAttribute('placeholder', t(elm.getAttribute('data-i18n-placeholder')));
    });
    // 同步 <html lang> 與文件標題
    document.documentElement.setAttribute('lang', current);
    const titleKey = document.body && document.body.getAttribute('data-i18n-title');
    if (titleKey) document.title = t(titleKey);
  }

  window.I18N = { LANGS, setLang, getLang, normalize, t, apply, DEFAULT_LANG };
